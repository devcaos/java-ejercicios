
public class ej28 {
    public static void main(String[] args) {
        // Declaración variable de la primera nota
        double nota1 = 7;
        // Declaración varible de la segunda nota
        double nota2 = 8;
        // Declaración variable de la tercera nota
        double nota3 = 6;
        // Cálculo de la media sumando las tres notas y dividiendo entre 3 (agrupando con paréntesis la operacion que se hará antes)
        double media = (nota1 + nota2 + nota3) / 3;
        
        // Imprime la nota media calculada
        System.out.println("La nota media es " + media);
    }
}